-- Migration 001: normalized Oracle schema.
-- Run with a dedicated development schema. Do not run against production without review.
-- Passwords are never stored here; authentication belongs to the identity provider.

CREATE TABLE member (
  member_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identity_uid VARCHAR2(128) NOT NULL UNIQUE,
  email VARCHAR2(254) NOT NULL UNIQUE,
  first_name VARCHAR2(80) NOT NULL,
  last_name VARCHAR2(80) NOT NULL,
  phone VARCHAR2(30),
  fitness_goal VARCHAR2(500),
  body_type VARCHAR2(80),
  member_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL
    CHECK (member_status IN ('ACTIVE','SUSPENDED','CANCELLED')),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE trainer (
  trainer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL UNIQUE REFERENCES member(member_id),
  bio VARCHAR2(1000),
  specialisation VARCHAR2(200) NOT NULL,
  approval_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
    CHECK (approval_status IN ('PENDING','APPROVED','REJECTED')),
  rating NUMBER(2,1) CHECK (rating BETWEEN 0 AND 5)
);

CREATE TABLE fitness_class (
  class_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_name VARCHAR2(120) NOT NULL,
  trainer_id NUMBER REFERENCES trainer(trainer_id),
  starts_at TIMESTAMP NOT NULL,
  duration_minutes NUMBER(4) NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
  capacity NUMBER(4) NOT NULL CHECK (capacity > 0),
  class_status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL
    CHECK (class_status IN ('SCHEDULED','CANCELLED','COMPLETED')),
  CONSTRAINT uq_class_start UNIQUE (class_name, starts_at)
);

CREATE TABLE booking (
  booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL REFERENCES member(member_id),
  class_id NUMBER NOT NULL REFERENCES fitness_class(class_id),
  booking_status VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL
    CHECK (booking_status IN ('CONFIRMED','CANCELLED','WAITLISTED','ATTENDED','NO_SHOW')),
  booked_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  cancelled_at TIMESTAMP,
  CONSTRAINT ck_booking_cancel_time CHECK (
    (booking_status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    OR (booking_status <> 'CANCELLED' AND cancelled_at IS NULL)
  ),
  CONSTRAINT uq_member_class_booking UNIQUE (member_id, class_id)
);

CREATE TABLE payment (
  payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL REFERENCES member(member_id),
  amount NUMBER(10,2) NOT NULL CHECK (amount > 0),
  currency CHAR(3) DEFAULT 'ZAR' NOT NULL CHECK (currency = 'ZAR'),
  payment_method VARCHAR2(12) NOT NULL CHECK (payment_method IN ('CASH','CARD','EFT')),
  payment_status VARCHAR2(16) DEFAULT 'PENDING' NOT NULL
    CHECK (payment_status IN ('PENDING','PAID','FAILED','REFUNDED')),
  reference_code VARCHAR2(80) UNIQUE,
  paid_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_payment_paid_at CHECK (
    (payment_status = 'PAID' AND paid_at IS NOT NULL)
    OR (payment_status <> 'PAID' AND paid_at IS NULL)
  )
);

CREATE TABLE attendance (
  attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL REFERENCES member(member_id),
  checked_in_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  checked_out_at TIMESTAMP,
  recorded_by_uid VARCHAR2(128),
  CONSTRAINT ck_attendance_times CHECK (
    checked_out_at IS NULL OR checked_out_at >= checked_in_at
  )
);

CREATE TABLE friend_request (
  friend_request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_member_id NUMBER NOT NULL REFERENCES member(member_id),
  receiver_member_id NUMBER NOT NULL REFERENCES member(member_id),
  request_status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL
    CHECK (request_status IN ('PENDING','ACCEPTED','DECLINED','CANCELLED')),
  requested_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  responded_at TIMESTAMP,
  CONSTRAINT ck_friend_not_self CHECK (sender_member_id <> receiver_member_id),
  CONSTRAINT uq_friend_pair UNIQUE (sender_member_id, receiver_member_id)
);

CREATE TABLE trainer_session (
  session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL REFERENCES member(member_id),
  trainer_id NUMBER NOT NULL REFERENCES trainer(trainer_id),
  starts_at TIMESTAMP NOT NULL,
  duration_minutes NUMBER(4) NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
  session_status VARCHAR2(16) DEFAULT 'REQUESTED' NOT NULL
    CHECK (session_status IN ('REQUESTED','CONFIRMED','CANCELLED','COMPLETED')),
  notes VARCHAR2(500)
);

CREATE TABLE exercise (
  exercise_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exercise_name VARCHAR2(120) NOT NULL UNIQUE,
  muscle_group VARCHAR2(80) NOT NULL,
  instructions CLOB NOT NULL,
  difficulty VARCHAR2(12) NOT NULL CHECK (difficulty IN ('BEGINNER','INTERMEDIATE','ADVANCED')),
  source_reference VARCHAR2(500)
);

CREATE TABLE invoice (
  invoice_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id NUMBER NOT NULL REFERENCES member(member_id),
  invoice_number VARCHAR2(40) NOT NULL UNIQUE,
  amount_due NUMBER(10,2) NOT NULL CHECK (amount_due > 0),
  due_date DATE NOT NULL,
  invoice_status VARCHAR2(12) DEFAULT 'UNPAID' NOT NULL
    CHECK (invoice_status IN ('UNPAID','PAID','OVERDUE','VOID')),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_booking_class_status ON booking(class_id, booking_status);
CREATE INDEX ix_booking_member_date ON booking(member_id, booked_at);
CREATE INDEX ix_payment_member_date ON payment(member_id, created_at);
CREATE INDEX ix_attendance_member_date ON attendance(member_id, checked_in_at);
CREATE INDEX ix_class_start ON fitness_class(starts_at);
CREATE INDEX ix_session_trainer_date ON trainer_session(trainer_id, starts_at);

